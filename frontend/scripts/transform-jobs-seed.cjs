/**
 * One-off helper: reads initialJobs from jobsStorage.js, outputs canonical mock shape
 * (date, address, addressDetail, participants, briefing, alerts) to initialJobsSeed.js
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const storagePath = path.join(root, "src", "utils", "jobsStorage.js");
const outPath = path.join(root, "src", "utils", "initialJobsSeed.js");

const s = fs.readFileSync(storagePath, "utf8");
const match = s.match(/export const initialJobs = (\[[\s\S]*?\n\]);/);
if (!match) throw new Error("Could not parse initialJobs from jobsStorage.js");

const arr = vm.runInNewContext(`(${match[1]})`, {});

function canon(j) {
  const out = { ...j };
  const date = j.workDate !== undefined ? j.workDate : j.date;
  const addr = j.shortRegion || j.address || "";
  const detail = j.fullAddress || j.addressDetail || "";
  delete out.workDate;
  delete out.shortRegion;
  delete out.shortAddress;
  delete out.fullAddress;
  delete out.applicants;
  out.date = date || "";
  out.address = addr;
  out.addressDetail = detail;
  out.participants = Array.isArray(j.participants)
    ? j.participants
    : Array.isArray(j.applicants)
      ? j.applicants
      : [];
  out.briefing = Array.isArray(j.briefing) ? j.briefing : [];
  out.alerts = Array.isArray(j.alerts) ? j.alerts : [];
  return out;
}

const next = arr.map(canon);
const id14 = [];
next.forEach((x, i) => {
  if (x.id === 14) id14.push(i);
});
if (id14.length === 2) {
  const lastIdx = id14[id14.length - 1];
  const row = next[lastIdx];
  next[lastIdx] = {
    ...row,
    id: 15,
    listImage: String(row.listImage || "").replace(/ildang-site-14/, "ildang-site-15"),
  };
}

const banner = `/**
 * Canonical mock job seed (see mockJobs.js / jobModel migrateJob).
 * Core fields: id, title, address, date, participants, briefing, alerts (+ domain extras).
 * Generated by scripts/transform-jobs-seed.cjs — edit source in jobsStorage then re-run if needed.
 */
`;

const body = `export const initialJobs = ${JSON.stringify(next, null, 2)};\n`;
fs.writeFileSync(outPath, banner + body, "utf8");
console.log("Wrote", outPath);
